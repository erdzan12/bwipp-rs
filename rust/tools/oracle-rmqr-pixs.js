// Dump bwip-js raw().pixs for a corpus of rMQR (Rectangular Micro
// QR, ISO 23941) symbols with FIXED (text, version, eclevel) so we
// can pin qrcode_native::encode_qr_at_metric byte-for-byte. Output
// is TSV to stdout:
//
//   label\ttext\tversion\teclevel\trows\tcols\tpixs-csv
//
// where `pixs-csv` is the comma-separated row-major bit array
// (length = rows*cols).
//
// Run from `node-sidecar/`:
//   node ../rust/tools/oracle-rmqr-pixs.js > ../rust/tests/fixtures/qrcode_native_rmqr_pixs.txt
//
// The Rust-side counterpart in rust/src/symbology/qrcode_native/
// mod.rs walks each row, asserting encode_qr_at_metric produces
// matching pixs. Pins the full Stage 15a-d pipeline against
// bwip-js byte-for-byte before any rMQR catalog cutover.
//
// ISO 23941 / BWIPP rMQR has 32 size variants and 2 valid EC
// levels (M and H). We cover a representative spread without
// exhausting the full 64-row matrix: small / medium / large widths
// × short / tall rows × both EC levels = 16 rows.

const { findBwipJs } = require("./_bwip_js_path.js");
const bwipp = require(findBwipJs(__dirname));

const cases = [
  // R7 row — shortest. Tests TL-finder y<rows gate + BR sub-finder.
  { label: "r7x43_m_hi", text: "HI", version: "R7x43", eclevel: "M" },
  { label: "r7x43_h_hi", text: "HI", version: "R7x43", eclevel: "H" },
  { label: "r7x77_m_hello", text: "HELLO", version: "R7x77", eclevel: "M" },
  { label: "r7x139_m_alpha", text: "ABCDEFGHIJKLMNOPQRST", version: "R7x139", eclevel: "M" },
  // R9 row.
  { label: "r9x43_m_hello", text: "HELLO", version: "R9x43", eclevel: "M" },
  { label: "r9x77_h_hello", text: "HELLO", version: "R9x77", eclevel: "H" },
  // R11 row — has the only fimax=98 (no alignment) variant.
  { label: "r11x27_m_hi", text: "HI", version: "R11x27", eclevel: "M" },
  { label: "r11x43_m_hello_world", text: "HELLO WORLD", version: "R11x43", eclevel: "M" },
  // R13 row.
  { label: "r13x27_m_hi", text: "HI", version: "R13x27", eclevel: "M" },
  { label: "r13x77_m_alpha", text: "ABCDEFGHIJKLMNOPQRST", version: "R13x77", eclevel: "M" },
  // R15 row.
  { label: "r15x43_m_hello", text: "HELLO", version: "R15x43", eclevel: "M" },
  { label: "r15x99_h_alpha", text: "ABCDEFGHIJ", version: "R15x99", eclevel: "H" },
  // R17 row — tallest.
  { label: "r17x43_m_hello_world", text: "HELLO WORLD", version: "R17x43", eclevel: "M" },
  { label: "r17x139_m_alpha_50", text: "A".repeat(50), version: "R17x139", eclevel: "M" },
  // High-EC + large size.
  { label: "r17x99_h_alpha_30", text: "B".repeat(30), version: "R17x99", eclevel: "H" },
  // Numeric-only fast path.
  { label: "r7x43_m_numeric", text: "12345", version: "R7x43", eclevel: "M" },
];

process.stdout.write("# Pixs goldens for qrcode_native rMQR end-to-end pipeline test.\n");
process.stdout.write("# Generated by rust/tools/oracle-rmqr-pixs.js (fixedeclevel=true).\n");
process.stdout.write("# Format: label<TAB>text<TAB>version<TAB>eclevel<TAB>rows<TAB>cols<TAB>pixs-csv\n");
for (const c of cases) {
  const raw = bwipp.raw("rectangularmicroqrcode", c.text, {
    version: c.version,
    eclevel: c.eclevel,
    fixedeclevel: true,
    includetext: false,
  });
  const r = raw[0];
  const flat = Array.from(r.pixs).map((p) => (p ? "1" : "0")).join(",");
  process.stdout.write(
    `${c.label}\t${c.text}\t${c.version}\t${c.eclevel}\t${r.pixy}\t${r.pixx}\t${flat}\n`,
  );
}
