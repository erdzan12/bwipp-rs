process.stdout.write("# Pixs goldens for qrcode_native end-to-end pipeline test.\n");
process.stdout.write("# Generated by rust/tools/oracle-qrcode-pixs.js (fixedeclevel=true).\n");
process.stdout.write("# Format: label<TAB>text<TAB>version<TAB>eclevel<TAB>width<TAB>pixs-csv\n");
for (const c of cases) {
  const bcid = c.sym || "qrcode";
  const raw = bwipp.raw(bcid, c.text, {
    version: c.version,
    eclevel: c.eclevel,
    fixedeclevel: true,
    includetext: false,
  });
  const r = raw[0];
  if (r.pixx !== r.pixy) {
    throw new Error(`non-square QR ${r.pixx}x${r.pixy} for ${c.label}`);
  }
  const flat = Array.from(r.pixs).map((p) => (p ? "1" : "0")).join(",");
  process.stdout.write(
    `${c.label}\t${c.text}\t${c.version}\t${c.eclevel}\t${r.pixx}\t${flat}\n`,
  );
}
